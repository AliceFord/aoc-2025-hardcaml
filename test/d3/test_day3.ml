let ( <--. ) = Bits.( <--. )

let string_to_char_list s =
  let rec exp i l =
    if i < 0 then l else exp (i - 1) (s.[i] :: l) in
  exp (String.length s - 1) []

let parse_d3_line l =
  let clist = string_to_char_list l in
  List.map clist ~f:(fun c -> int_of_char c - int_of_char '0')

let d3_from_file filename =
  let chan = In_channel.create filename in
  let rec loop acc =
    match In_channel.input_line chan with
    | None ->
        In_channel.close chan;
        List.rev acc
    | Some line ->
        loop (parse_d3_line line :: acc)
  in
  loop []

let simple_testbench part (sim : Harness.Sim.t) =
  let inputs = Cyclesim.inputs sim in
  let outputs = Cyclesim.outputs sim in
  let cycle ?n () = Cyclesim.cycle ?n sim in
  (* Helper function for inputting one value *)
  let feed_input n =
    inputs.data_in <--. n;
    inputs.data_in_valid := Bits.vdd;
    cycle ();
    inputs.data_in_valid := Bits.gnd;
    (* no cycle needed here *)
  in
  let feed_break () =
    inputs.data_sep := Bits.vdd;
    cycle ();
    inputs.data_sep := Bits.gnd;
    (* no cycle needed here *)
  in
  (* Reset the design *)
  inputs.clear := Bits.vdd;
  cycle ();
  inputs.clear := Bits.gnd;
  cycle ();
  (* Pulse the start signal *)
  inputs.start := Bits.vdd;
  inputs.part <--. part;
  cycle ();
  inputs.start := Bits.gnd;
  cycle ();
  (* Input some data *)
  List.iter (d3_from_file "/mnt/c/Users/olive/Documents/coding/aoc2025/hardcaml_template_project/d3_partial.txt") ~f:(fun xs -> 
    List.iter xs ~f:(fun n -> feed_input n);
    feed_break ()
  );
  inputs.finish := Bits.vdd;
  cycle ();
  inputs.finish := Bits.gnd;
  cycle ();
  while not (Bits.to_bool !(outputs.sum_valid)) do
    cycle ()
  done;
  let sum = Bits.to_unsigned_int !(outputs.sum_value) in
  print_s [%message "Result" (sum : int)];
  cycle ~n:2 ()
;;

